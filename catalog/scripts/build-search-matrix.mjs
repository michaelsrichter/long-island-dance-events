#!/usr/bin/env node
// Builds catalog/search-matrix.json (the town-by-town Web IQ queries) from catalog/search-places.json
// and src/data/long-island-places.json. Every Long Island place is searched once: under its own name
// or inside its group. Hub places get every dance and music term; small places get the core terms.
//
// The output uses the same "groups" shape as catalog/search-queries.json (group = search place), so
// catalog/scripts/webiq-search.mjs can run it. --check fails when the committed matrix is stale.
//
// Usage: node catalog/scripts/build-search-matrix.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';

const placesFile = JSON.parse(readFileSync('src/data/long-island-places.json', 'utf8'));
const config = JSON.parse(readFileSync('catalog/search-places.json', 'utf8'));
const OUT = 'catalog/search-matrix.json';

const county = new Map(placesFile.places.map((p) => [p.name, p.county]));
const errors = [];
const memberOf = new Map();
for (const [group, members] of Object.entries(config.groups)) {
  if (!county.has(group)) errors.push(`Group "${group}" is not a place in long-island-places.json.`);
  for (const m of members) {
    if (!county.has(m)) errors.push(`Group member "${m}" is not a place in long-island-places.json.`);
    if (memberOf.has(m)) errors.push(`"${m}" is in two groups.`);
    if (config.groups[m]) errors.push(`"${m}" is both a group and a member.`);
    memberOf.set(m, group);
  }
}
const small = new Set(config.small);
for (const s of small) {
  if (!county.has(s)) errors.push(`Small place "${s}" is not a place in long-island-places.json.`);
  if (memberOf.has(s)) errors.push(`Small place "${s}" is a group member; list its group instead.`);
}
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const allTerms = [...config.terms.dance, ...config.terms.music];
const query = (place, term) => config.queryFormat.replace('{place}', place).replace('{term}', term);
const searchPlaces = placesFile.places
  .map((p) => p.name)
  .filter((name) => !memberOf.has(name))
  .sort((a, b) => a.localeCompare(b));

const places = {};
const groups = {};
const seen = new Set();
for (const name of searchPlaces) {
  const tier = small.has(name) ? 'small' : 'hub';
  const terms = tier === 'small' ? config.terms.core : allTerms;
  places[name] = { county: county.get(name), tier, members: config.groups[name] ?? [] };
  groups[name] = terms.map((t) => query(name, t)).filter((q) => !seen.has(q.toLowerCase()) && seen.add(q.toLowerCase()));
}

const hubs = Object.values(places).filter((p) => p.tier === 'hub').length;
const queries = Object.values(groups).reduce((n, g) => n + g.length, 0);
const matrix = {
  about:
    'Town-by-town Web IQ discovery queries, generated by catalog/scripts/build-search-matrix.mjs from catalog/search-places.json. Do not edit by hand. Group names are the search places.',
  totals: { placesCovered: county.size, searchPlaces: searchPlaces.length, hubPlaces: hubs, smallPlaces: searchPlaces.length - hubs, queries },
  places,
  groups,
};
const text = JSON.stringify(matrix, null, 1) + '\n';
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {}
  if (current.replace(/\r\n/g, '\n') !== text) {
    console.error(`${OUT} is out of date. Run: node catalog/scripts/build-search-matrix.mjs`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${queries} queries).`);
} else {
  writeFileSync(OUT, text);
  console.log(`${county.size} places -> ${searchPlaces.length} search places (${hubs} hub, ${searchPlaces.length - hubs} small) -> ${queries} queries.`);
}
